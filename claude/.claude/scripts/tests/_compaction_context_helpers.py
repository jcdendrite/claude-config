"""Builders for the transcript record shapes compaction-context.py reads, shared by the test_compaction_context_*.py files.

Each builder follows the shape docs/precompact-hook-behavior.md's survival findings section records. A field a builder
sets by default is removed by passing ABSENT, so a twin record differs from its base in one keyword.
"""
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path

_SCRIPT = Path(__file__).parent.parent / "compaction-context.py"
_spec = importlib.util.spec_from_file_location("compaction_context", _SCRIPT)
compaction_context = importlib.util.module_from_spec(_spec)
sys.path.insert(0, str(_SCRIPT.parent))
_spec.loader.exec_module(compaction_context)

ABSENT = object()
HUMAN_ORIGIN = {"kind": "human"}


def skill_dir(name: str) -> str:
    return f"/work/repo/.claude/skills/{name}"


SKILL_DIR = skill_dir("scratch")
SKILL_PATH = f"{SKILL_DIR}/SKILL.md"
BRANCH = "feature/scratch"
PLAN_LINE_PREFIX = "Plan file at this branch's plan path:"


def _apply_overrides(rec: dict, overrides: dict) -> dict:
    for key, value in overrides.items():
        if value is ABSENT:
            rec.pop(key, None)
        else:
            rec[key] = value
    return rec


def user_prompt(text="a typed prompt", *, origin=HUMAN_ORIGIN, entrypoint="cli", **overrides) -> dict:
    """A typed prompt as an interactive session records it: `origin.kind` human, entrypoint cli, promptSource typed."""
    rec = {"type": "user", "message": {"role": "user", "content": text}}
    return _apply_overrides(rec, {"origin": origin, "entrypoint": entrypoint, "promptSource": "typed", **overrides})


def headless_prompt(text="a headless prompt", *, origin=ABSENT, entrypoint="sdk-cli", **overrides) -> dict:
    """A `claude -p` prompt: no `origin`, entrypoint sdk-cli, promptSource and turnOrigin sdk."""
    return user_prompt(text, origin=origin, entrypoint=entrypoint, **{"promptSource": "sdk", "turnOrigin": "sdk", **overrides})


def _origin_less_cli_record(content, **overrides) -> dict:
    rec = {"type": "user", "message": {"role": "user", "content": content}, "entrypoint": "cli"}
    return _apply_overrides(rec, overrides)


def slash_invocation(name="scratch", args="some args") -> dict:
    """A skill slash invocation; a bare one (args=None) carries no `<command-args>` tag."""
    text = f"<command-message>{name}</command-message>\n<command-name>/{name}</command-name>"
    if args is not None:
        text += f"\n<command-args>{args}</command-args>"
    return user_prompt(text)


def builtin_command(name="/compact") -> dict:
    return _origin_less_cli_record(f"<command-name>{name}</command-name>\n<command-args></command-args>")


def local_command_stdout(text="Compacted") -> dict:
    return _origin_less_cli_record(f"<local-command-stdout>{text}</local-command-stdout>")


def bash_input(command="ls") -> dict:
    return _origin_less_cli_record(f"<bash-input>{command}</bash-input>")


def bash_stdout(output="file.txt") -> dict:
    return _origin_less_cli_record(f"<bash-stdout>{output}</bash-stdout><bash-stderr></bash-stderr>", turnOrigin="human")


def skill_load(directory=SKILL_DIR, *, text="1. First step.", **overrides) -> dict:
    """The `isMeta` record the harness writes when a skill loads, on every invocation path.

    directory=None leaves the first line with the prefix alone.
    """
    first_line = "Base directory for this skill" + ("" if directory is None else f": {directory}")
    body = f"{first_line}\n\n# Scratch skill\n\n{text}"
    rec = _origin_less_cli_record([{"type": "text", "text": body}], isMeta=True, promptId="prompt-1")
    return _apply_overrides(rec, overrides)


def already_loaded_record(text="Launching skill: scratch") -> dict:
    """What a Skill-tool call on an already-loaded skill wrote: an `isMeta` string that is not a skill load."""
    return _origin_less_cli_record(text, isMeta=True, sourceToolUseID="toolu_1")


def compact_caveat(text="Caveat: the messages below were generated by the user while running local commands.") -> dict:
    return _origin_less_cli_record(text, isMeta=True)


def compact_summary(text="This session is being continued from a previous conversation.", *, automatic=False) -> dict:
    rec = _origin_less_cli_record(text, isCompactSummary=True, promptId="prompt-1")
    if automatic:
        rec.update({"summarizedTurnPromptUuids": ["uuid-1"], "turnOrigin": "human"})
    return rec


def interrupt_marker(*, tool_run=False, **overrides) -> dict:
    text = "[Request interrupted by user for tool use]" if tool_run else "[Request interrupted by user]"
    rec = _origin_less_cli_record(
        [{"type": "text", "text": text}], promptId="prompt-1", interruptedMessageId="msg-1",
    )
    return _apply_overrides(rec, overrides)


def pasted_prompt(body="pasted body", **overrides) -> dict:
    """A multi-line paste: two leading newlines, a `pasted_content` wrapper with an id, a closing tag with the same id."""
    text = f'\n\n<pasted_content id="paste-1">{body}</pasted_content id="paste-1">'
    return user_prompt(text, **overrides)


def tool_result_record(output="tool output", **overrides) -> dict:
    rec = _origin_less_cli_record(
        [{"type": "tool_result", "tool_use_id": "toolu_1", "content": output}],
        toolUseResult={"stdout": output},
    )
    return _apply_overrides(rec, overrides)


def skill_tool_result_record(**overrides) -> dict:
    """The `tool_result` record a `Skill` tool call writes: `toolUseResult` keys commandName and success."""
    return tool_result_record("Launching skill: scratch", toolUseResult={"commandName": "scratch", "success": True}, **overrides)


def answer_record(answer="an answer", **overrides) -> dict:
    """An AskUserQuestion answer: one `tool_result` block, `toolUseResult` keys annotations, answers and questions."""
    rec = _origin_less_cli_record(
        [{"type": "tool_result", "tool_use_id": "toolu_2", "content": answer}],
        toolUseResult={"annotations": {}, "answers": {"q": answer}, "questions": []},
    )
    return _apply_overrides(rec, overrides)


def task_notification(summary="done") -> dict:
    text = f"<task-notification><status>completed</status><summary>{summary}</summary></task-notification>"
    origin = {"kind": "task-notification", "producer": "bash", "runId": "run-1"}
    return user_prompt(text, origin=origin, promptSource="system", turnOrigin="task_notification")


def assistant_tool_use(tool_name="Bash") -> dict:
    return {
        "type": "assistant",
        "message": {"role": "assistant", "content": [{"type": "tool_use", "id": "toolu_1", "name": tool_name, "input": {}}]},
    }


def skill_tool_use() -> dict:
    tool_use = {"type": "tool_use", "id": "toolu_1", "name": "Skill", "input": {"skill": "scratch", "args": "/secret/args"}}
    return {"type": "assistant", "message": {"role": "assistant", "content": [tool_use]}}


def invoked_skills_attachment() -> dict:
    """The attachment the harness writes after a compaction: skill content cut at a limit, a path naming no file on disk."""
    skill = {"name": "scratch", "path": "/nonexistent/skills/scratch/SKILL.md", "content": "1. First step."}
    return {"type": "attachment", "attachment": {"type": "invoked_skills", "skills": [skill]}}


def attachment_record(text="hook output") -> dict:
    return {"type": "attachment", "attachment": {"type": "hook_additional_context", "content": text}}


def compact_boundary(*, automatic=False, preserved_uuids=()) -> dict:
    rec = {"type": "system", "subtype": "compact_boundary", "compactMetadata": {"trigger": "auto" if automatic else "manual"}}
    if automatic:
        rec["compactMetadata"]["preservedMessages"] = {"anchorUuid": "uuid-0", "uuids": list(preserved_uuids)}
    return rec


def manual_compaction_records() -> list:
    """The records a manual `/compact` writes after the compacted turns, in recorded order."""
    return [
        compact_boundary(), compact_summary(), compact_caveat(), builtin_command(), local_command_stdout(),
        invoked_skills_attachment(), attachment_record("hook block"),
    ]


def automatic_compaction_records(preserved_prompt_uuid="uuid-p1") -> list:
    """The records an automatic compaction writes, whose boundary lists one preserved prompt uuid."""
    return [
        compact_boundary(automatic=True, preserved_uuids=[preserved_prompt_uuid]),
        attachment_record(), attachment_record(), attachment_record(), invoked_skills_attachment(),
        compact_summary(automatic=True), attachment_record("hook block"),
    ]


def at_checkout(rec: dict, *, branch=BRANCH, cwd=ABSENT) -> dict:
    """rec with `gitBranch` and `cwd` set; pass ABSENT for either to leave it off."""
    return _apply_overrides(dict(rec), {"gitBranch": branch, "cwd": cwd})


def sidechain(rec: dict) -> dict:
    return {**rec, "isSidechain": True}


def with_headless_markers(rec: dict) -> dict:
    """The same record carrying the three values a `claude -p` prompt carries: the only difference from the recorded shape."""
    return {**rec, "entrypoint": "sdk-cli", "promptSource": "sdk", "turnOrigin": "sdk"}


_FENCED_MESSAGE_RE = re.compile(r"^(~{3,})\n(.*?)\n\1$", re.DOTALL | re.MULTILINE)


def quoted_messages(block: str) -> list[str]:
    """The fenced message bodies of a block, oldest first."""
    return [match.group(2) for match in _FENCED_MESSAGE_RE.finditer(block)]


def write_transcript(directory: Path, records: list) -> Path:
    path = directory / "session.jsonl"
    path.write_text("\n".join(json.dumps(rec) for rec in records) + "\n", encoding="utf-8")
    return path


def block_for(directory: Path, records: list) -> str:
    return compaction_context.build_state_block(write_transcript(directory, records))


def make_plan_checkout(root: Path, slug="scratch", *, git_as_file=False) -> Path:
    """A checkout root holding `.git` and `.claude/plans/<slug>.md`; returns the plan file."""
    root.mkdir(parents=True, exist_ok=True)
    if git_as_file:
        (root / ".git").write_text("gitdir: /elsewhere/.git/worktrees/scratch\n")
    else:
        (root / ".git").mkdir(exist_ok=True)
    plan = root / ".claude" / "plans" / f"{slug}.md"
    plan.parent.mkdir(parents=True, exist_ok=True)
    plan.write_text("# Plan\n")
    return plan


def run_cli(transcript: Path | str, stdout=subprocess.PIPE) -> subprocess.CompletedProcess:
    """Runs the script in a subprocess. stdout may be a file object or descriptor to make the block's write fail."""
    return subprocess.run(
        [sys.executable, str(_SCRIPT), "state", "--transcript", str(transcript)],
        stdout=stdout, stderr=subprocess.PIPE, check=False,
    )
